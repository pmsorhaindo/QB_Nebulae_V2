#!/usr/bin/env python3
"""
CosmicFlux Offline Render Harness

Mimics conductor.generate_orc to build a complete Csound orchestra+score,
then renders test signals through the instrument with various control scenarios.
"""

import os
import sys
import json
import subprocess
import numpy as np
import soundfile as sf
from pathlib import Path

# Ensure we can find the instrument
DEV_DIR = Path(__file__).parent
INSTR_DIR = DEV_DIR.parent
INSTR_FILE = INSTR_DIR / "cosmicflux.instr"
OUTPUT_DIR = DEV_DIR / "output"
SCENARIOS_DIR = DEV_DIR / "scenarios"

def parse_nebconfig(instr_content):
    """Extract nebconfig settings from instrument file"""
    config = {"sr": 48000, "ksmps": 64}
    
    in_config = False
    for line in instr_content.split('\n'):
        line = line.strip()
        if line == "nebconfigbegin":
            in_config = True
        elif line == "nebconfigend":
            in_config = False
        elif in_config and ',' in line:
            parts = line.split(',')
            key = parts[0].strip()
            if key == "sr":
                config["sr"] = int(parts[1].strip())
            elif key == "ksmps":
                config["ksmps"] = int(parts[1].strip())
    
    return config

def get_instr_body(instr_content):
    """Extract the instrument body (after nebconfigend)"""
    parts = instr_content.split("nebconfigend", 1)
    if len(parts) == 2:
        return parts[1]
    return instr_content

